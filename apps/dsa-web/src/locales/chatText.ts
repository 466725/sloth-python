export function getChatSkillText(skill: SkillInfo, language: UiLanguage): Pick<SkillInfo, 'name' | 'description'> {
  if (language === 'zh' || !Object.hasOwn(EN_SKILLS, skill.id)) return skill;
  return EN_SKILLS[skill.id];
}

export function getChatSkillName(nameOrId: string, language: UiLanguage): string {
  if (language === 'zh') return nameOrId;
  if (Object.hasOwn(EN_SKILLS, nameOrId)) return EN_SKILLS[nameOrId].name;
  if (nameOrId === '通用') return en.general;
  return Object.values(EN_SKILLS).find((skill) => skill.zhName === nameOrId)?.name ?? nameOrId;
}
